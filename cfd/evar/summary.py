#!/usr/bin/env python3
"""Compile the EVAR results into results/evar/RESULTS.md and a summary figure.

    python3 evar/summary.py --site worst
"""
from __future__ import annotations

import argparse
import csv
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), "results", "evar")


def _csv(path):
    return list(csv.DictReader(open(path))) if os.path.exists(path) else []


def _f(x, nd=3):
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default="worst")
    ap.add_argument("--graft", default="graft-coarse")
    a = ap.parse_args()
    val = json.load(open(os.path.join(RES, "validation-coarse", "validation.json")))
    gm_p = os.path.join(RES, a.graft, "graft_metrics.json")
    gm = json.load(open(gm_p)) if os.path.exists(gm_p) else None
    sd = os.path.join(RES, "patch", f"site-{a.site}")
    pm = _csv(os.path.join(sd, "patch_metrics.csv"))
    pl = _csv(os.path.join(sd, "platelets", "platelet_summary.csv"))
    site = json.load(open(os.path.join(sd, "site_and_calibration.json"))) if os.path.exists(
        os.path.join(sd, "site_and_calibration.json")) else {}
    ver = {}
    for f in os.listdir(os.path.join(RES, "patch")) if os.path.isdir(os.path.join(RES, "patch")) else []:
        if f.startswith("verify_quasisteady_"):
            ver[f[len("verify_quasisteady_"):-5]] = json.load(open(os.path.join(RES, "patch", f)))

    L = ["# DentiFlow EVAR results (computational)", "",
         "Generated by `evar/summary.py` from the result files. Mesh: coarse vessel-scale preset; "
         "patch at 3 um. **Preliminary until the digitised waveform replaces the generic one.**", "",
         "## 1. Method check: Womersley validation (25 mm tube, Newtonian)", "",
         "| Quantity | CFD | Analytical |", "|---|---|---|",
         f"| TAWSS (Pa) | {val['TAWSS_cfd_Pa']} | {val['TAWSS_analytical_Pa']} |",
         f"| OSI | {val['OSI_cfd']} | {val['OSI_analytical']} |",
         f"| Peak WSS (Pa) | {val['peak_tau_cfd_Pa']} | {val['peak_tau_analytical_Pa']} |",
         f"| RMS error over the cycle | {val['rms_error_pct_of_peak']}% of peak | |", ""]
    if gm:
        L += ["## 2. Vessel scale: idealized bifurcated endograft (resting infrarenal flow)", "",
              "| Segment | TAWSS (Pa) | area < 0.4 Pa | OSI | area OSI > 0.25 | RRT median (1/Pa) | RRT 95th pct |",
              "|---|---|---|---|---|---|---|"]
        for k, s in gm["segments"].items():
            L.append(f"| {k} | {s['TAWSS_Pa']} | {s['lowWSS_area_pct']}% | {s['OSI']} | {s['OSI_gt_0.25_area_pct']}% | "
                     f"{s['RRT_median_perPa']} | {s['RRT_p95_perPa']} |")
        L += ["", "Patch sites (2 mm neighbourhood averages):", ""]
        for nm, s in gm["patch_sites"].items():
            L.append(f"- **{nm.replace('_', ' ')}**: x = {s['centre_mm'][0]} mm ({s['segment']}, {s['side']} wall), "
                     f"TAWSS {s['TAWSS_Pa']} Pa, OSI {s['OSI']}, RRT {s['RRT_perPa']} 1/Pa; cross-flow "
                     f"{s['perp_to_principal_rms_pct']}% of the principal component (RMS)")
        pc = gm.get("periodicity_TAWSS_change_last2cycles_pct", {})
        if pc:
            L += ["", f"Cycle-to-cycle change of probe TAWSS (last two cycles): max {max(pc.values()):.1f}%."]
        L += ["", "![graft maps](" + a.graft + "/graft_maps.png)", ""]
    if pm:
        L += [f"## 3. Texture scale: wall patch at the {a.site} limb site", "",
              f"Site waveform: TAWSS {_f(site.get('TAWSS_site_Pa'))} Pa, OSI {_f(site.get('OSI_site'))}.", "",
              "| Design | TAWSS (Pa) | vs smooth | area < 50% smooth TAWSS | OSI | RRT median | WSSG p95 (Pa/mm) | "
              "slow-flow vol (um) | vs smooth | wetted area |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for r in pm:
            L.append(f"| {r['design']} | {_f(r['TAWSS_Pa'])} | {r.get('TAWSS_Pa_vs_smooth_pct', '')}% | "
                     f"{r.get('area_below_half_smooth_TAWSS_pct', '')}% | {_f(r['OSI'])} | {_f(r['RRT_median_perPa'], 1)} | "
                     f"{_f(r['WSSG_p95_Pa_mm'], 1)} | {_f(float(r['slow_flow_volume_mm3_per_mm2']) * 1e3, 1)} | "
                     f"{r.get('slow_flow_volume_mm3_per_mm2_vs_smooth_pct', '')}% | {_f(r['wetted_area_ratio'], 2)} |")
        L += ["", "Slow-flow volume is the fluid layer per unit graft area moving slower than fluid 5 um above a "
              "smooth wall (smooth = 5 um by construction).", "",
              "![patch comparison](patch/site-" + a.site + "/patch_comparison.png)", ""]
    if ver:
        L += ["Quasi-steady check (full time-dependent patch run vs rebuild):", ""]
        for k, v in ver.items():
            L.append(f"- {k}: TAWSS {v['TAWSS_pulsatile_Pa']:.4f} vs {v['TAWSS_quasisteady_Pa']:.4f} Pa "
                     f"({v['TAWSS_diff_pct']:+.2f}%), face-wise RMS {v['TAWSS_facewise_rms_diff_pct']:.2f}%, "
                     f"OSI {v['OSI_pulsatile']:.3f} vs {v['OSI_quasisteady']:.3f}")
        L.append("")
    if pl:
        L += ["## 4. Platelet deposition on the reactive graft surface", "",
              f"{pl[0]['duration_s']} s of real time, 3 seeds per design, mean +/- SD across seeds.", "",
              "| Design | deposited / mm2 | vs smooth | z vs smooth | adhered / mm2 wetted | aggregated / mm2 | "
              "% in lowest third of texture |", "|---|---|---|---|---|---|---|"]
        for r in pl:
            L.append(f"| {r['design']} | {r['deposited_per_mm2_mean']} +/- {r['deposited_per_mm2_sd']} | "
                     f"{r.get('deposited_vs_smooth_pct', '')}% | {r.get('z_vs_smooth', '')} | "
                     f"{r['adhered_per_mm2_wetted_mean']} | {r['aggregated_per_mm2_mean']} | {r.get('pct_in_lower_third') or ''} |")
        L.append("")
    open(os.path.join(RES, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    # summary figure: TAWSS change, slow-flow change, platelet change
    if pm:
        names = [r["design"] for r in pm]
        fig, axs = plt.subplots(1, 3 if pl else 2, figsize=(15 if pl else 10, 4.5), sharey=True)
        v1 = [float(r.get("TAWSS_Pa_vs_smooth_pct") or 0) for r in pm]
        v2 = [float(r.get("slow_flow_volume_mm3_per_mm2_vs_smooth_pct") or 0) for r in pm]
        col = ["0.55" if n in ("smooth", "pet") else ("C2" if "flush" in n or "riblet" in n else "C0") for n in names]
        axs[0].barh(names, v1, color=col)
        axs[0].set_title("TAWSS vs smooth graft (%)\n(higher = less stasis-prone)", fontsize=9)
        axs[1].barh(names, v2, color=col)
        axs[1].set_title("slow-flow volume vs smooth (%)\n(lower = less near-wall stasis)", fontsize=9)
        if pl:
            pmap = {r["design"]: r for r in pl}
            v3 = [float(pmap[n].get("deposited_vs_smooth_pct") or 0) if n in pmap else 0 for n in names]
            e3 = [100 * float(pmap[n]["deposited_per_mm2_sd"]) / float(pmap["smooth"]["deposited_per_mm2_mean"])
                  if n in pmap else 0 for n in names]
            axs[2].barh(names, v3, xerr=e3, color=col)
            axs[2].set_title("platelet deposition vs smooth (%)\n(lower = better), +/- SD over seeds", fontsize=9)
        for ax in axs:
            ax.axvline(0, color="k", lw=0.7)
            ax.tick_params(labelsize=8)
        axs[0].invert_yaxis()
        fig.suptitle(f"EVAR graft-limb textures at the {a.site} limb site (grey: controls, green: height-neutral)",
                     fontsize=10)
        fig.tight_layout()
        fig.savefig(os.path.join(RES, "summary.png"), dpi=150)


if __name__ == "__main__":
    main()
